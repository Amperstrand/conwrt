#!/bin/sh
# cross-mipsel.sh — Cross-build conwrt-agent for OpenWrt mipsel_24kc (static, soft-float)
#
# Produces a fully-static soft-float MIPS32r2 binary that runs on any
# mipsel_24kc OpenWrt target (mt7621-class: COVR-X1860, NR7101, ...).
#
# Usage:
#   ./scripts/cross-mipsel.sh [--keep-debug]
#
# Requires: curl, sha256sum, tar (zstd), git, rustup with nightly installed
#   rustup toolchain install nightly
#   (rust-src is auto-installed by this script if missing)
#
# Background — why this recipe is shaped the way it is (live-verified on a
# D-Link COVR-X1860 A1 / mt7621 / MIPS 1004Kc / OpenWrt 25.12.5, 2026-10-14):
#
#   1. rustup ships NO prebuilt std for mips/mipsel (tier 3 since ~1.86)
#      -> nightly + `-Z build-std=std,panic_abort` builds std from source.
#   2. Ubuntu's mipsel-linux-gnu cross-glibc is HARD-float. The mt7621's
#      1004Kc has no FPU and OpenWrt kernels ship without the FPU emulator,
#      so hard-float binaries die with SIGILL (a static "hello" SIGILLs too).
#      -> use the official OpenWrt toolchain tarball: soft-float mipsel_24kc
#         musl, the exact toolchain that built the target firmware.
#   3. rustc passes BARE crt filenames (crt1.o, crti.o, crtbegin.o, ...)
#      on the link line for musl targets, expecting a self-contained sysroot
#      dir that does not exist for tier-3 mipsel. GNU ld resolves bare
#      operands only against the CWD — NOT via -L search — so the link fails
#      with "cannot find crt1.o".
#      -> generated link-wrapper.sh rewrites the bare names to full toolchain
#         paths before exec'ing gcc.
#   4. rustc's musl link line asks for -lunwind, which the toolchain does not
#      ship (OpenWrt musl uses gcc's unwinder).
#      -> bridge symlink libunwind.a -> libgcc_eh.a.
#   5. `-static-pie` would need rcrt1.o handling that trips cross-gcc;
#      `-C relocation-model=static` makes rustc pass plain `-static`.
#
# Verified on-device (COVR-X1860 A1, OpenWrt 25.12.5):
#   conwrt-agent runs natively; controller CLI round-trips
#   `agent info` / `agent lease` (exclusive grant + conflict denial +
#   shared grant) over TCP:8400. See issue #109.
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

# ── Toolchain pin (bump these three together) ────────────────────────
TOOLCHAIN_URL="https://downloads.openwrt.org/releases/25.12.5/targets/ramips/mt7621/openwrt-toolchain-25.12.5-ramips-mt7621_gcc-14.3.0_musl.Linux-x86_64.tar.zst"
TOOLCHAIN_SHA256="04316e081dcaea0394d3a8eca761500c91d7d54e9d49ccb8f855ae257ea4f995"
TOOLCHAIN_TARBALL="${TOOLCHAIN_URL##*/}"
TOOLCHAIN_TOPDIR="openwrt-toolchain-25.12.5-ramips-mt7621_gcc-14.3.0_musl.Linux-x86_64"
TOOLCHAIN_INNER="toolchain-mipsel_24kc_gcc-14.3.0_musl"

TARGET=mipsel-unknown-linux-musl

CACHE="${CONWRT_MIPS_CACHE:-$HOME/.cache/conwrt/mipsel}"
LINKDIR="$CACHE/link"
TC="$CACHE/$TOOLCHAIN_TOPDIR/$TOOLCHAIN_INNER"
OUT="${CARGO_TARGET_DIR:-$ROOT/target}/$TARGET/release/conwrt-agent"

KEEP_DEBUG=0
[ "${1:-}" = "--keep-debug" ] && KEEP_DEBUG=1

mkdir -p "$CACHE"

# ── 1. Fetch + verify + unpack the OpenWrt toolchain (cached) ────────
if [ ! -x "$TC/bin/mipsel-openwrt-linux-musl-gcc" ]; then
    echo "==> downloading OpenWrt toolchain (~46 MB) to $CACHE"
    curl -fSL --retry 3 -o "$CACHE/$TOOLCHAIN_TARBALL" "$TOOLCHAIN_URL"
    echo "$TOOLCHAIN_SHA256  $CACHE/$TOOLCHAIN_TARBALL" | sha256sum -c -
    if tar --zstd -xf "$CACHE/$TOOLCHAIN_TARBALL" -C "$CACHE" 2>/dev/null; then
        : # GNU tar with --zstd
    else
        tar -xf "$CACHE/$TOOLCHAIN_TARBALL" -C "$CACHE" # bsdtar auto-detects zstd
    fi
fi

# ── 2. Locate gcc's private lib dir (version-robust) ─────────────────
GCCDIR=""
for d in "$TC"/lib/gcc/mipsel-openwrt-linux-musl/*/; do GCCDIR="${d%/}"; break; done
if [ -z "$GCCDIR" ] || [ ! -f "$GCCDIR/crtbegin.o" ]; then
    echo "error: gcc lib dir not found under $TC" >&2
    exit 1
fi

# ── 3. Generate link helpers (wrapper + libunwind bridge) ────────────
mkdir -p "$LINKDIR"
ln -sf "$GCCDIR/libgcc_eh.a" "$LINKDIR/libunwind.a"

cat > "$LINKDIR/paths.sh" <<EOF
TC="$TC"
GCCDIR="$GCCDIR"
EOF

cat > "$LINKDIR/link-wrapper.sh" <<'EOF'
#!/bin/sh
# Generated by scripts/cross-mipsel.sh — do not edit.
# Rewrites rustc's BARE crt filenames to full toolchain paths (GNU ld does
# not search -L dirs for bare operands), then execs gcc with --sysroot.
SELF_DIR=$(cd "$(dirname "$0")" && pwd)
. "$SELF_DIR/paths.sh"

n=$#
while [ "$n" -gt 0 ]; do
    a="$1"
    shift
    case "$a" in
        crt1.o)     a="$TC/lib/crt1.o" ;;
        crti.o)     a="$TC/lib/crti.o" ;;
        crtn.o)     a="$TC/lib/crtn.o" ;;
        crtbegin.o) a="$GCCDIR/crtbegin.o" ;;
        crtend.o)   a="$GCCDIR/crtend.o" ;;
    esac
    set -- "$@" "$a"
    n=$((n - 1))
done

# STAGING_DIR silences gcc.bin's harmless "not defined" warning.
STAGING_DIR="$TC"
export STAGING_DIR

exec "$TC/bin/mipsel-openwrt-linux-musl-gcc.bin" "--sysroot=$TC" "$@"
EOF
chmod +x "$LINKDIR/link-wrapper.sh"

# ── 4. Prerequisites: nightly toolchain + rust-src ───────────────────
if ! rustup toolchain list | grep -q '^nightly'; then
    echo "error: nightly toolchain required (build-std). Install with:" >&2
    echo "  rustup toolchain install nightly" >&2
    exit 1
fi
if ! rustup component list --toolchain nightly 2>/dev/null | grep -q '^rust-src.*(installed)'; then
    echo "==> installing rust-src for nightly"
    rustup component add rust-src --toolchain nightly
fi

# ── 5. Build (std from source; fully static, no PIE) ─────────────────
# Explicit --target-dir keeps OUT deterministic even when the invoking
# checkout's .cargo/config.toml points elsewhere (shared ~/.cargo-target).
echo "==> building conwrt-agent for $TARGET"
(
    cd "$ROOT"
    CARGO_TARGET_MIPSEL_UNKNOWN_LINUX_MUSL_LINKER="$LINKDIR/link-wrapper.sh" \
    RUSTFLAGS="-C target-feature=+crt-static -C relocation-model=static -C link-arg=-L$TC/lib -C link-arg=-L$GCCDIR -C link-arg=-L$LINKDIR" \
    cargo +nightly build --release -p conwrt-agent \
        --target "$TARGET" \
        --target-dir "${CARGO_TARGET_DIR:-$ROOT/target}" \
        -Z build-std=std,panic_abort
)

# ── 6. Strip with the toolchain's own strip (unless --keep-debug) ────
if [ "$KEEP_DEBUG" -ne 1 ]; then
    STRIP_BIN="$TC/bin/mipsel-openwrt-linux-musl-strip"
    if [ -x "$STRIP_BIN" ]; then
        "$STRIP_BIN" "$OUT"
    elif command -v mipsel-linux-gnu-strip >/dev/null 2>&1; then
        mipsel-linux-gnu-strip "$OUT"
    else
        echo "note: no mipsel strip found — leaving debug info in place"
    fi
fi

# ── 7. Report ─────────────────────────────────────────────────────────
echo "==> built: $OUT"
ls -la "$OUT" | awk '{print "    size: " $5 " bytes"}'
sha256sum "$OUT" | awk '{print "    sha256: " $1}'
file "$OUT" 2>/dev/null | sed 's/^/    /' || true
echo "deploy:  scp -O '$OUT' root@<device>:/tmp/conwrt-agent   # dropbear: -O (no sftp)"
