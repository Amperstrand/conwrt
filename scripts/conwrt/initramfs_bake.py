#!/usr/bin/env python3
"""initramfs-bake — emit the profile-baked image overlay for a zycast
stage-1 boot (#784, cut 1: the offline slice).

Today's zycast'd stage-1 boot is a stock 192.168.1.1 + armed DHCP —
the rogue window the model JSONs warn about. This driver produces the
image-side overlay that closes it: the SAME profile pipeline the ASU
flow uses (`build_plan` → `asu_defaults_script`, subshell-isolated
blocks with `|| exit 1` retry semantics) laid out in the OpenWrt
`FILES=` convention:

    <out>/files/etc/uci-defaults/99-conwrt-identity   # the fragment
    <out>/README-build.md                             # the SDK recipe

The SDK/full build itself stays a bench lane (disk + acceptance
gated); everything this driver emits is verified offline. uci-defaults
re-run on every ramdisk boot, so each stage-1 boot carries the
identity — persistence is irrelevant at this stage (#784 §1e).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

sys.path.insert(0, str(REPO_ROOT / "scripts"))

from config import load_config  # noqa: E402
from model_loader import resolve_model_any  # noqa: E402
from profile.builder import build_plan  # noqa: E402
from profile.overlay import _validate_lan_ip  # noqa: E402


def bake(model_id: str, out_dir: Path, *, ssh_key_path: str | None = None,
         hostname: str = "", lan_ip: str = "") -> Path:
    """Write the overlay tree; returns the files/ root."""
    model = resolve_model_any(model_id)
    if model is None:
        raise ValueError(
            f"unknown model '{model_id}': no models/*.json matches it as "
            "model id, underscored id, or openwrt.profile")

    cfg = load_config()
    if lan_ip:
        # The builder only emits the static-LAN block when cfg.lan_ip is set
        # BEFORE build_plan runs — mutating cfg after the call was a no-op
        # (found 2026-11-25: --lan-ip was silently dropped from the fragment).
        _validate_lan_ip(lan_ip)
        cfg.lan_ip = lan_ip
        cfg.lan_ip_mode = "static"
    plan = build_plan(
        cfg,
        mode="asu_build",
        model_capabilities=model.get("capabilities", []),
        ssh_key_path=ssh_key_path,
        wan_ssh=False,
        tofb=False,
        disable_dhcp=True,   # the rogue-DHCP discipline — always off in stage 1
        hostname=hostname,
        lan_ip_mode="static" if lan_ip else "",
    )

    fragment = plan.asu_defaults_script()
    if not fragment:
        raise ValueError(
            "profile pipeline produced an empty identity fragment — "
            "refusing to bake a no-op overlay (the stage would boot "
            "indistinguishable from stock)")

    files_root = out_dir / "files" / "etc" / "uci-defaults"
    files_root.mkdir(parents=True, exist_ok=True)
    (files_root / "99-conwrt-identity").write_text(fragment + "\n")

    (out_dir / "README-build.md").write_text(_build_recipe(model, lan_ip))
    return out_dir / "files"


def _build_recipe(model: dict, lan_ip: str) -> str:
    target = model.get("openwrt", {}).get("target", "<target/subtarget>")
    profile = model.get("openwrt", {}).get("profile", "<profile>")
    vendor = model.get("vendor", model.get("id", "?"))
    return f"""# Profile-baked initramfs build recipe ({vendor}, {profile})

Generated by `conwrt initramfs-bake` (#784 cut 1). The overlay in
`files/` carries the stage-1 identity (LAN IP, DHCP triple off, SSH
key, hostname) as an uci-defaults script — re-run on EVERY ramdisk
boot, so persistence is irrelevant at this stage.

## Build (SDK lane — bench-gated)

1. Set up the OpenWrt SDK for `{target}` (bench precedent: the NR7101
   WWAN-D SDK build notes).
2. Copy the overlay into the build tree:
       cp -r files/* <sdk>/files/
3. Build the initramfs image for the profile:
       make image PROFILE={profile} FILES=<sdk>/files/
4. The emitted initramfs is the zycast payload (same image class;
   Z-Loader acceptance needs the same discipline as #782 — bench).

## Why not imagebuilder

The imagebuilder cannot emit initramfs for this target (verified on
25.12.6 {target}: no initramfs in profiles.json) — the SDK/full-build
lane is the only path (docs/zycast.md §1e).

## Verification (offline)

- The fragment is the profile pipeline's own output
  (`asu_defaults_script`): subshell-isolated blocks, `|| exit 1`
  retry semantics — a failed block keeps the file for the next boot
  instead of consuming a half-applied one (#229).
- `conwrt initramfs-bake` refuses an EMPTY fragment rather than
  baking a no-op overlay.
{f"- Stage-1 LAN address: {lan_ip}" if lan_ip else ""}
"""


def cmd_initramfs_bake(args: argparse.Namespace) -> int:
    try:
        files_root = bake(
            args.model_id, Path(args.out),
            ssh_key_path=args.ssh_key, hostname=args.hostname,
            lan_ip=args.lan_ip)
    except ValueError as exc:
        print(f"initramfs-bake: {exc}", file=sys.stderr)
        return 1
    print(str(files_root))
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="conwrt initramfs-bake",
        description="emit the profile-baked image overlay for a zycast "
                    "stage-1 boot (#784 cut 1 — offline slice)")
    p.add_argument("--model-id", required=True, help="registry model id")
    p.add_argument("--out", default="initramfs-overlay",
                   help="output directory (default: ./initramfs-overlay)")
    p.add_argument("--ssh-key", default=None,
                   help="public key path to bake (default: config)")
    p.add_argument("--hostname", default="", help="stage-1 hostname")
    p.add_argument("--lan-ip", default="",
                   help="static stage-1 LAN IP (default: profile config)")
    return p


def main(argv: list[str] | None = None) -> int:
    return cmd_initramfs_bake(build_parser().parse_args(argv))


if __name__ == "__main__":
    raise SystemExit(main())
