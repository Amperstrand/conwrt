# ------------------------------------------------------------------ run / exit codes

def _isolated_env(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setenv("CONWRT_CONFIG", str(tmp_path / "no-config.toml"))
    for var in ("LG_COORDINATOR", "LG_EXPORTER_HOST"):
        monkeypatch.delenv(var, raising=False)


def test_doctor_unconfigured_exits_zero_all_absent(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture) -> None:
    _isolated_env(monkeypatch, tmp_path)
    code = bd.run_doctor(bd.Options(places=tmp_path / "none.json",
                                    exporter=tmp_path / "none.yaml"))
    out = capsys.readouterr().out
    assert code == 0
    assert "L1 coordinator: ABSENT" in out
    assert "UNCONFIGURED" in out


def test_doctor_degraded_coordinator_exits_one(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture) -> None:
    _isolated_env(monkeypatch, tmp_path)

    def refused(_endpoint, timeout=None):
        raise OSError(61, "connection refused")
    monkeypatch.setattr(bd.socket, "create_connection", refused)
    code = bd.run_doctor(bd.Options(places=tmp_path / "none.json",
                                    exporter=tmp_path / "none.yaml",
                                    coordinator="192.168.13.221:20408"))
    out = capsys.readouterr().out
    assert code == 1
    assert "L1 coordinator: DEGRADED" in out
    assert "DEGRADED — see level lines" in out


def test_doctor_never_prints_registry_passwords(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture) -> None:
    _isolated_env(monkeypatch, tmp_path)
    bd.run_doctor(bd.Options(places=_registry(tmp_path), exporter=_exporter(tmp_path)))
    assert "SECRETPW" not in capsys.readouterr().out


def test_crosscheck_mode_exit_codes(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                    capsys: pytest.CaptureFixture) -> None:
    _isolated_env(monkeypatch, tmp_path)
    assert bd.run_doctor(bd.Options(mode="crosscheck", places=_registry(tmp_path),
                                    exporter=_exporter(tmp_path))) == 0
    drifted = [{"name": "ap-lan9", "mac": "", "dut_ip": "", "reset_allowed": True}]
    assert bd.run_doctor(bd.Options(mode="crosscheck", places=_registry(tmp_path, drifted),
                                    exporter=_exporter(tmp_path))) == 1
    assert "DRIFT" in capsys.readouterr().out
    # CI checkout: no local registries at all — skipped, green
    assert bd.run_doctor(bd.Options(mode="crosscheck", places=tmp_path / "none.json",
                                    exporter=tmp_path / "none.yaml")) == 0


def test_crosscheck_mode_unparsable_input_exits_one(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    _isolated_env(monkeypatch, tmp_path)
    bad = tmp_path / "places.json"
    bad.write_text("{not json", encoding="utf-8")
    assert bd.run_doctor(bd.Options(mode="crosscheck", places=bad,
                                    exporter=_exporter(tmp_path))) == 1


